import { forwardRef, type SVGProps } from 'react'

type IconProps = SVGProps<SVGSVGElement> & { size?: number | string }
export const Icon = forwardRef<SVGSVGElement, IconProps & { name: string }>(function Icon({ name, size = 24, children, ...props }, ref) {
  return <svg ref={ref} width={size} height={size} viewBox="0 0 24 24" fill="none" strokeWidth={1.5} aria-hidden={props['aria-label'] ? undefined : true} {...props}><use href={`/icons/iconoir.svg#${name}`}/>{children}</svg>
})
function icon(name: string) {
  return forwardRef<SVGSVGElement, IconProps>(function NamedIcon(props, ref) { return <Icon ref={ref} name={name} {...props}/> })
}

